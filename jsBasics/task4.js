// 4.1 Площа кола
const radius = 5;
const circleArea = (Math.PI * radius ** 2).toFixed(2);
console.log(`Площа кола: ${circleArea}`);

// 4.2 Площа прямокутника
const length = 8;
const width = 4;
const rectangleArea = (length * width).toFixed(2);
console.log(`Площа прямокутника: ${rectangleArea}`);

// 4.3 Об'єм циліндра
const cylinderHeight = 10;
const cylinderVolume = (Math.PI * radius ** 2 * cylinderHeight).toFixed(2);
console.log(`Об'єм циліндра: ${cylinderVolume}`);